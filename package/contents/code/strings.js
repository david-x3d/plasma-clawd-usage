// "auto" (or empty) - the system language when there is a table for it.
function lang(l) {
    if (!l || l === "auto") l = String(Qt.locale().name).split("_")[0];
    return Strings[l] ? l : "en";
}

// T(l, key[, default]) - string for the language, falling back to English, then to default.
function T(l, key, def) {
    var s = Strings[lang(l)][key];
    if (s === undefined) s = Strings.en[key];
    if (s === undefined) return def === undefined ? key : def;
    return s;
}

// .NET-style "{0}" / "{1:00}" formatting.
function F(fmt) {
    var a = Array.prototype.slice.call(arguments, 1);
    if (a.length === 1 && Array.isArray(a[0])) a = a[0];
    return String(fmt).replace(/\{(\d+)(?::(0+))?\}/g, function (m, i, pad) {
        var v = a[+i];
        if (v === undefined || v === null) v = "";
        v = String(v);
        if (pad) while (v.length < pad.length) v = "0" + v;
        return v;
    });
}

// "1 session" / "5 sessions"; Russian has three plural forms.
function count(l, n, key) {
    var f = T(l, "plural." + key);
    if (f.length === 2) return n + " " + (n === 1 ? f[0] : f[1]);
    var d = n % 10, h = n % 100;
    if (n === 1) return n + " " + f[0];
    if (d === 1 && h !== 11 && l !== "pl") return n + " " + f[0];
    if (d >= 2 && d <= 4 && (h < 12 || h > 14)) return n + " " + f[1];
    return n + " " + f[2];
}
